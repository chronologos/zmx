#!/usr/bin/env bash
# Guards the fork's upstream-isolation invariants (src/fork/README.md). Run after `jj rebase`.
set -euo pipefail
cd "$(dirname "$0")/.."

fail() { echo "fork-check: FAIL — $1" >&2; exit 1; }

# --- Seams: `// [fork]` lines in upstream-owned files ---------------------------------
# A rebase that drops a seam compiles fine and silently disables the fork's daemon code;
# one that duplicates it runs that code twice. Change this number with the seam itself.
seams=2
seam_lines=$(rg -n '//\s*\[fork\]\s*$' \
  --glob '!src/fork/**' --glob '!bridge/**' --glob '!scripts/**' . || true)
seam_count=$(printf '%s' "$seam_lines" | grep -c . || true)
[[ "$seam_count" -eq "$seams" ]] \
  || fail "expected $seams [fork] seam lines outside src/fork/, bridge/ and scripts/, found $seam_count
$seam_lines"

# --- Anchor: the upstream line the daemon seam sits after -----------------------------
# Checked even while seams=0, so an upstream rewrite of daemonLoop is noticed before the
# seam has to be re-placed by hand.
anchor='var vt_stream = term.vtStream();'
anchor_file=src/loop.zig
anchor_count=$(rg -cF "$anchor" "$anchor_file" || true)
if [[ "${anchor_count:-0}" -ne 1 ]]; then
  elsewhere=$(rg -lF "$anchor" src --glob '!src/fork/**' || true)
  fail "expected exactly one \`$anchor\` in $anchor_file, found ${anchor_count:-0}${elsewhere:+ (present in: $elsewhere)}"
fi

# --- src/fork/ imports only what the README allows ------------------------------------
bad_imports=$(rg -n '@import\("' src/fork --glob '*.zig' \
  | rg -v '@import\("(std|ghostty-vt|\.\./loop\.zig|[A-Za-z0-9_]+\.zig)"\)' || true)
[[ -z "$bad_imports" ]] \
  || fail "src/fork/ may import only std, ghostty-vt, ../loop.zig and its own files:
$bad_imports"

# --- Pin and nix lock agree -----------------------------------------------------------
# The lock is regenerated by hand, so a pin bump that forgets it breaks only the flake. Only
# the fork's own pin is ours to keep in step; with upstream's pin, the lock is upstream's too.
# With no `main` to compare against, the pin counts as ours.
pin=$(sed -nE 's/.*\.hash = "(ghostty-[^"]+)".*/\1/p' build.zig.zon)
[[ -n "$pin" ]] || fail "no ghostty hash found in build.zig.zon"
upstream_pin=$(git show main:build.zig.zon 2>/dev/null \
  | sed -nE 's/.*\.hash = "(ghostty-[^"]+)".*/\1/p' || true)
if [[ "$pin" == "$upstream_pin" ]]; then
  lock="pin is upstream's"
else
  rg -qF "\"$pin\"" build.zig.zon2json-lock \
    || fail "build.zig.zon2json-lock is stale: it has no entry for $pin (see src/fork/README.md)"
  lock="lock matches pin"
fi

echo "fork-check: OK — $seams seams, anchor present, $lock"
